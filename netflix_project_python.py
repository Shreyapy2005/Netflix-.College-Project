# Duplicate Records

df.duplicated().sum()

#Dirty Values - N/A, NULL, Blank, space

df.replace(
    ['N/A', 'NULL', '', ' '], np.nan, inplace=True
)

df.isnull().sum()

# Extra Space Remove

df = df.apply(lambda x: x.str.strip() if x.dtype == "object" else x)

df.info()

# Standardize Text

df["show_id"] = df["show_id"].str.title()

df["type"] = df["type"].str.title()

df["title"] = df["title"].str.title()

df["director"] = df["director"].str.title()

df["cast"] = df["cast"].str.title()

df["country"] = df["country"].str.title()

df["duration"] = df["duration"].str.title()

df["listed_in"] = df["listed_in"].str.title()

df["description"] = df["description"].str.title()

# count country

df["country"].value_counts()

df.describe()

df.info()

#date cleaning

df['date_added'] = pd.to_datetime(df['date_added'], errors = 'coerce')

# Missing Values Handle

df["director"] = df["director"].fillna("Unknown")

df["cast"] = df["cast"].fillna("Unknown")

df["country"] = df["country"].fillna("Unknown")

df["rating"] = df["rating"].fillna("Unknown")

df["duration"] = df["duration"].fillna("Unknown")

#Feature Engineering

#Added Year
df["Added_Year"] = df["date_added"].dt.year

#Added Month
df["Added_Month"] = df["date_added"].dt.month

#Added Quarter
df["Added_Quarter"] = (
    "Q" +
    df["date_added"].dt.quarter.astype("Int64").astype(str)
)

#Content Year
current_year = pd.Timestamp.now().year
df["Content_Year"] = current_year - df["release_year"]

#Duration Value
df["Duration_Value"] = pd.to_numeric(
    df["duration"].str.extract(r"(\d+)")[0], errors="coerce"
)

#Duration Unit
df["Duration_Unit"] = df["duration"].str.extract(r"([A-Za]+)")

#Content_Category
df["Content_Category"] = df["type"].map({
    "Movie": "Film",
    "TV Show": "TV Series"
})

#Release Decade

df["Release_Decade"] = (
    (df["release_year"] // 10)*10
).astype("Int64")

feature_columns = [
    "title",
    "type",
    "date_added",
    "release_year",
    "Added_Year",
    "Added_Month",
    "Added_Quarter",
    "Content_Year",
    "duration",
    "Duration_Value",
    "Duration_Unit",
    "Content_Category",
    "Release_Decade",
]

